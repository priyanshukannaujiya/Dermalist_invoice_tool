export interface InvoiceExcelPayload {
  invoice_number: string;
  invoice_date: string;
  payment_terms?: string;
  service_description: string;
  quantity?: number;
  unit_price?: number;
  taxable_value: number;
  discount?: number;
  subtotal_less_discount: number;
  balance_due: number;
  video_link?: string | null;
  creator: {
    id?: number | null;
    name: string;
    address?: string | null;
    email?: string | null;
    phone?: string | null;
    pan?: string | null;
    upi_id?: string | null;
    bank_account?: string | null;
    ifsc?: string | null;
    account_holder?: string | null;
    bank_name?: string | null;
    is_msme?: boolean;
    msme_registration_no?: string | null;
  };
}

/**
 * Sanitizes the Excel workbook zip package to ensure strict OpenXML schema compliance:
 * 1. ExcelJS places <pageSetUpPr> before <outlinePr> in <sheetPr>, violating the ISO OpenXML schema.
 *    This causes Microsoft Excel to flag the workbook as corrupted ("Repaired") and strip the worksheet.
 *    We reorder <outlinePr> before <pageSetUpPr>.
 * 2. Removes invalid negative DPI attributes (4294967295) generated by ExcelJS.
 */
async function sanitizeExcelBuffer(buffer: Buffer): Promise<Buffer> {
  const zip = await JSZip.loadAsync(buffer);
  const sheetFile = zip.file("xl/worksheets/sheet1.xml");

  if (sheetFile) {
    let sheetXml = await sheetFile.async("string");

    // Fix OpenXML schema sequence in <sheetPr>
    sheetXml = sheetXml.replace(
      /(<pageSetUpPr[^>]*\/>)(<outlinePr[^>]*\/>)/g,
      "$2$1"
    );

    // Remove invalid 32-bit unsigned DPI values (4294967295)
    sheetXml = sheetXml.replace(/\s*horizontalDpi="4294967295"/g, "");
    sheetXml = sheetXml.replace(/\s*verticalDpi="4294967295"/g, "");

    zip.file("xl/worksheets/sheet1.xml", sheetXml);
  }

  const cleanNodeBuffer = await zip.generateAsync({
    type: "nodebuffer",
    compression: "DEFLATE",
    compressionOptions: { level: 6 },
  });

  return cleanNodeBuffer;
}

export async function generateInvoiceExcelBuffer(data: InvoiceExcelPayload): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.calcProperties.fullCalcOnLoad = true;

  const templatePath = path.resolve(
    process.cwd(),
    process.env.TEMPLATE_PATH || "templates/non gst invoice format - Dermalist (2).xlsx"
  );

  // Fetch authoritative creator details and bank account from database
  let c = { ...data.creator };
  if (c.id || c.name) {
    try {
      const dbCreator = await getCreatorByNameOrId(c.id, c.name);
      if (dbCreator) {
        c = {
          ...c,
          id: dbCreator.id,
          name: c.name || dbCreator.name,
          address: c.address || dbCreator.address || "",
          email: c.email || dbCreator.email || "",
          phone: c.phone || dbCreator.phone || "",
          pan: dbCreator.pan || c.pan || "",
          upi_id: dbCreator.upi_id || c.upi_id || "",
          bank_account: dbCreator.bank_account || c.bank_account || "",
          ifsc: dbCreator.ifsc || c.ifsc || "",
          account_holder: dbCreator.account_holder || c.account_holder || dbCreator.name,
          bank_name: dbCreator.bank_name || c.bank_name || "",
          is_msme: dbCreator.is_msme ?? c.is_msme ?? false,
          msme_registration_no: dbCreator.msme_registration_no || c.msme_registration_no || "",
        };
      }
    } catch (err) {
      console.warn("Excel export: Creator database enrichment error:", err);
    }
  }

  c.bank_name = resolveBankName(c.bank_name, c.ifsc);

  const hasTemplate = fs.existsSync(templatePath);

  if (hasTemplate) {
    await workbook.xlsx.readFile(templatePath);
    workbook.calcProperties.fullCalcOnLoad = true;
    const ws = workbook.worksheets[0];

    // 1. Creator Header Information
    ws.getCell("B2").value = c.name || "Creator Name";
    ws.getCell("B3").value = c.address || "";
    ws.getCell("B5").value = c.email ? `Email ID: ${c.email}` : "Email ID:";
    ws.getCell("B6").value = c.phone ? `Contact Number: ${c.phone}` : "Contact Number";
    ws.getCell("B7").value = c.pan ? `Pan Number : ${c.pan}` : "Pan Number : ";

    // 2. Invoice Metadata
    ws.getCell("D9").value = `Invoice No: ${data.invoice_number}`;
    ws.getCell("D10").value = `Invoice Date:${data.invoice_date}`;
    ws.getCell("D11").value = `Terms of Payment: ${data.payment_terms || "Bank Transfer Or UPICode"}`;
    ws.getCell("D14").value = `MSME Regsistration Status : ${c.is_msme ? "YES" : "NO"}`;
    ws.getCell("D15").value = `If Yes : MSME No :${c.msme_registration_no || (c.is_msme ? "UDYAM-MH-18-0490710" : "N/A")}`;

    // 3. Line Items
    const qty = data.quantity || 1;
    const descText = qty > 1 ? `${qty} x ${data.service_description}` : data.service_description;
    ws.getCell("B18").value = descText;
    const taxableVal = Number(data.taxable_value) || 0;
    const discountVal = Number(data.discount) || 0;
    const balanceDueVal = Math.max(0, taxableVal - discountVal);

    ws.getCell("D18").value = taxableVal;
    ws.getCell("D18").numFmt = "#,##0.00";

    // Video Link
    if (data.video_link) {
      ws.getCell("B20").value = `Video Link- ${data.video_link}`;
    } else {
      ws.getCell("B20").value = "Video Link- ";
    }

    // Clear unused rows D19-D28
    for (let r = 19; r <= 28; r++) {
      if (r !== 20) {
        ws.getCell(`B${r}`).value = null;
      }
      ws.getCell(`D${r}`).value = null;
    }

    // 4. Totals & Formulas (Fixed double subtraction bug: D32 = D31)
    ws.getCell("D29").value = { formula: "SUM(D18:D28)", result: taxableVal };
    ws.getCell("D29").numFmt = "#,##0.00";

    ws.getCell("D30").value = discountVal;
    ws.getCell("D30").numFmt = "#,##0.00";

    ws.getCell("D31").value = {
      formula: "D29-D30",
      result: balanceDueVal,
    };
    ws.getCell("D31").numFmt = "#,##0.00";

    ws.getCell("D32").value = {
      formula: "D31",
      result: balanceDueVal,
    };
    ws.getCell("D32").numFmt = "#,##0.00";

    // 5. Creator Banking Details
    ws.getCell("B32").value = c.upi_id ? `UPI ID : ${c.upi_id}` : "UPI ID :";
    ws.getCell("B33").value = c.bank_account ? `Bank Account No:- ${c.bank_account}` : "Bank Account No:-";

    const ifscText = `IFSC:- ${c.ifsc || ""}`;
    const holderText = `Name of Accountholder:- ${c.account_holder || c.name || ""}`;
    const bankText = `Name of Bank:- ${c.bank_name || ""}`;
    const totalChars = ifscText.length + holderText.length + bankText.length;
    const padding = Math.max(2, Math.floor((92 - totalChars) / 2));
    const padStr = " ".repeat(padding);

    ws.getCell("B34").value = `${ifscText}${padStr}${holderText}${padStr}${bankText}`;

    const rawBuffer = await workbook.xlsx.writeBuffer();
    return await sanitizeExcelBuffer(Buffer.from(rawBuffer));
  } else {
    // Generate clean workbook with exact layout and styling
    const ws = workbook.addWorksheet("Invoice", {
      views: [{ showGridLines: true }],
    });

    ws.columns = [
      { width: 4 },  // A
      { width: 44 }, // B
      { width: 22 }, // C
      { width: 28 }, // D
      { width: 6 },  // E
    ];

    // Header Title
    ws.mergeCells("B1:D1");
    const titleCell = ws.getCell("B1");
    titleCell.value = "INVOICE";
    titleCell.font = { name: "Arial", size: 16, bold: true, color: { argb: "FF0F172A" } };
    titleCell.alignment = { horizontal: "center", vertical: "middle" };

    // Creator info
    ws.mergeCells("B2:C2");
    ws.getCell("B2").value = c.name;
    ws.getCell("B2").font = { name: "Arial", size: 11, bold: true };

    ws.mergeCells("B3:C3");
    ws.getCell("B3").value = c.address || "";
    ws.getCell("B3").font = { name: "Arial", size: 9 };

    ws.getCell("B5").value = `Email ID: ${c.email || ""}`;
    ws.mergeCells("B6:C6");
    ws.getCell("B6").value = `Contact Number: ${c.phone || ""}`;
    ws.getCell("B7").value = `Pan Number : ${c.pan || ""}`;

    // Bill To
    ws.getCell("B9").value = "BILL TO";
    ws.getCell("B9").font = { name: "Arial", size: 10, bold: true };
    ws.getCell("B10").value = "B M M RETAIL PRIVATE LIMITED";
    ws.getCell("B10").font = { name: "Arial", size: 10, bold: true };
    ws.getCell("B11").value = "THIRD, 307 A, FAIZ E QUTBI BUILDING,";
    ws.getCell("B12").value = "PLOT NO 375, Narsi Natha Street,";
    ws.getCell("B13").value = "Masjid Bander Maharashtra, 400009";
    ws.getCell("B14").value = "Contact - 88509 80156";
    ws.getCell("B15").value = "Email ID - info@dermalist.in";

    // Meta right column
    ws.getCell("D9").value = `Invoice No: ${data.invoice_number}`;
    ws.getCell("D9").font = { name: "Arial", size: 10, bold: true };
    ws.getCell("D10").value = `Invoice Date:${data.invoice_date}`;
    ws.getCell("D11").value = `Terms of Payment: ${data.payment_terms || "Bank Transfer Or UPICode"}`;
    ws.getCell("D14").value = `MSME Regsistration Status : ${c.is_msme ? "YES" : "NO"}`;
    ws.getCell("D15").value = `If Yes : MSME No :${c.msme_registration_no || (c.is_msme ? "UDYAM-MH-18-0490710" : "N/A")}`;

    // Items table header
    ws.mergeCells("B17:C17");
    ws.getCell("B17").value = "DESCRIPTION";
    ws.getCell("B17").font = { name: "Arial", size: 10, bold: true };
    ws.getCell("D17").value = "Taxable Value";
    ws.getCell("D17").font = { name: "Arial", size: 10, bold: true };
    ws.getCell("D17").alignment = { horizontal: "right" };

    // Line item row 18
    ws.mergeCells("B18:C18");
    const qty = data.quantity || 1;
    ws.getCell("B18").value = qty > 1 ? `${qty} x ${data.service_description}` : data.service_description;
    const taxableVal = Number(data.taxable_value) || 0;
    const discountVal = Number(data.discount) || 0;
    const balanceDueVal = Math.max(0, taxableVal - discountVal);

    ws.getCell("D18").value = taxableVal;
    ws.getCell("D18").numFmt = "#,##0.00";
    ws.getCell("D18").alignment = { horizontal: "right" };

    // Video link row 20
    ws.mergeCells("B20:C20");
    ws.getCell("B20").value = `Video Link- ${data.video_link || ""}`;

    // Totals
    ws.getCell("C29").value = "SUBTOTAL";
    ws.getCell("C29").font = { bold: true };
    ws.getCell("D29").value = { formula: "SUM(D18:D28)", result: taxableVal };
    ws.getCell("D29").numFmt = "#,##0.00";
    ws.getCell("D29").alignment = { horizontal: "right" };

    ws.getCell("B30").value = "Thank you for your business!";
    ws.getCell("C30").value = "DISCOUNT";
    ws.getCell("C30").font = { bold: true };
    ws.getCell("D30").value = discountVal;
    ws.getCell("D30").numFmt = "#,##0.00";
    ws.getCell("D30").alignment = { horizontal: "right" };

    ws.getCell("B31").value = "Signature:-";
    ws.getCell("C31").value = "SUBTOTAL LESS DISCOUNT";
    ws.getCell("C31").font = { bold: true };
    ws.getCell("D31").value = {
      formula: "D29-D30",
      result: balanceDueVal,
    };
    ws.getCell("D31").numFmt = "#,##0.00";
    ws.getCell("D31").alignment = { horizontal: "right" };

    ws.getCell("C32").value = "Balance Due";
    ws.getCell("C32").font = { bold: true };
    ws.getCell("D32").value = {
      formula: "D31",
      result: balanceDueVal,
    };
    ws.getCell("D32").numFmt = "#,##0.00";
    ws.getCell("D32").alignment = { horizontal: "right" };

    // Banking details
    ws.getCell("B32").value = `UPI ID : ${c.upi_id || ""}`;
    ws.getCell("B33").value = `Bank Account No:- ${c.bank_account || ""}`;

    const ifscFallback = `IFSC:- ${c.ifsc || ""}`;
    const holderFallback = `Name of Accountholder:- ${c.account_holder || c.name || ""}`;
    const bankFallback = `Name of Bank:- ${c.bank_name || ""}`;
    const totalFallbackChars = ifscFallback.length + holderFallback.length + bankFallback.length;
    const padFallback = Math.max(2, Math.floor((92 - totalFallbackChars) / 2));
    const padFallbackStr = " ".repeat(padFallback);

    ws.getCell("B34").value = `${ifscFallback}${padFallbackStr}${holderFallback}${padFallbackStr}${bankFallback}`;

    const rawBuffer = await workbook.xlsx.writeBuffer();
    return await sanitizeExcelBuffer(Buffer.from(rawBuffer));
  }
}
